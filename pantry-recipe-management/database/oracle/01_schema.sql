-- Pantry & Recipe Management System
-- Oracle reference schema. The managed WebDev runtime uses the equivalent MySQL/TiDB migration in drizzle/.

CREATE TABLE users (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(160) NOT NULL,
  email VARCHAR2(320) NOT NULL UNIQUE,
  password_hash VARCHAR2(255),
  cooking_level VARCHAR2(20) DEFAULT 'BEGINNER' NOT NULL,
  CONSTRAINT users_cooking_level_ck CHECK (cooking_level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED'))
);

CREATE TABLE categories (
  cat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label VARCHAR2(120) NOT NULL UNIQUE,
  shelf_life_days NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT categories_shelf_life_ck CHECK (shelf_life_days >= 0)
);

CREATE TABLE ingredients (
  ingredient_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(160) NOT NULL UNIQUE,
  default_unit VARCHAR2(32) NOT NULL,
  cat_id NUMBER NOT NULL REFERENCES categories(cat_id)
);

CREATE TABLE suppliers (
  sup_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(160) NOT NULL,
  contact VARCHAR2(320)
);

CREATE TABLE purchase_log (
  purchase_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id),
  ingredient_id NUMBER NOT NULL REFERENCES ingredients(ingredient_id),
  sup_id NUMBER REFERENCES suppliers(sup_id),
  purchase_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  quantity_purchased NUMBER(14,3) NOT NULL,
  unit VARCHAR2(32) NOT NULL,
  total_price NUMBER(14,2) DEFAULT 0 NOT NULL,
  CONSTRAINT purchase_log_quantity_ck CHECK (quantity_purchased > 0),
  CONSTRAINT purchase_log_price_ck CHECK (total_price >= 0)
);

CREATE TABLE pantry_items (
  item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id),
  ingredient_id NUMBER NOT NULL REFERENCES ingredients(ingredient_id),
  purchase_id NUMBER REFERENCES purchase_log(purchase_id),
  quantity NUMBER(14,3) NOT NULL,
  unit VARCHAR2(32) NOT NULL,
  expiry_date DATE,
  CONSTRAINT pantry_items_quantity_ck CHECK (quantity > 0)
);

CREATE TABLE recipes (
  recipe_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(240) NOT NULL,
  steps CLOB NOT NULL,
  cook_time_min NUMBER NOT NULL,
  difficulty_level VARCHAR2(20) DEFAULT 'BEGINNER' NOT NULL,
  utensil_count NUMBER DEFAULT 0 NOT NULL,
  source VARCHAR2(20) DEFAULT 'MANUAL' NOT NULL,
  source_url VARCHAR2(1000),
  rating NUMBER(3,2),
  CONSTRAINT recipes_time_ck CHECK (cook_time_min > 0),
  CONSTRAINT recipes_difficulty_ck CHECK (difficulty_level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
  CONSTRAINT recipes_source_ck CHECK (source IN ('MANUAL', 'WEB_RETRIEVED')),
  CONSTRAINT recipes_rating_ck CHECK (rating IS NULL OR (rating >= 0 AND rating <= 5))
);

CREATE TABLE recipe_ingredients (
  ri_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id NUMBER NOT NULL REFERENCES recipes(recipe_id) ON DELETE CASCADE,
  ingredient_id NUMBER NOT NULL REFERENCES ingredients(ingredient_id),
  quantity_required NUMBER(14,3) NOT NULL,
  unit VARCHAR2(32) NOT NULL,
  CONSTRAINT recipe_ingredients_quantity_ck CHECK (quantity_required > 0),
  CONSTRAINT recipe_ingredients_unique UNIQUE (recipe_id, ingredient_id)
);

CREATE TABLE cooking_log (
  cook_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id),
  recipe_id NUMBER NOT NULL REFERENCES recipes(recipe_id),
  cooked_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE dietary_tags (
  tag_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id NUMBER NOT NULL REFERENCES recipes(recipe_id) ON DELETE CASCADE,
  label VARCHAR2(100) NOT NULL
);

-- user_id is included for household-isolated reporting while waste remains ingredient-level.
CREATE TABLE waste_log (
  waste_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id),
  ingredient_id NUMBER NOT NULL REFERENCES ingredients(ingredient_id),
  quantity_wasted NUMBER(14,3) NOT NULL,
  unit VARCHAR2(32) NOT NULL,
  expired_on DATE NOT NULL,
  CONSTRAINT waste_log_quantity_ck CHECK (quantity_wasted > 0)
);

CREATE INDEX pantry_items_user_ingredient_ix ON pantry_items(user_id, ingredient_id);
CREATE INDEX pantry_items_expiry_ix ON pantry_items(user_id, expiry_date);
CREATE INDEX recipe_ingredients_recipe_ix ON recipe_ingredients(recipe_id);
CREATE INDEX cooking_log_user_date_ix ON cooking_log(user_id, cooked_at);
CREATE INDEX waste_log_user_date_ix ON waste_log(user_id, expired_on);

CREATE OR REPLACE TRIGGER pantry_items_positive_quantity_trg
BEFORE INSERT OR UPDATE OF quantity ON pantry_items
FOR EACH ROW
BEGIN
  IF :NEW.quantity <= 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'Pantry quantity must be greater than zero');
  END IF;
END;
